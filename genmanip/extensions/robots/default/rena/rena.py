"""
Rena (rena-labs-ai): fixed-base 6-DOF arm + 1-DOF finger gripper on a wheeled chassis.

Robot USD and URDF come from a rena-description checkout ($RENA_DESCRIPTION, default: next to
rena-sim). configs/robots/curobo/rena.yml and configs/cameras/rena.yml are generated by
rena-sim's datagen/genmanip_rena_config.py.
"""

import os
from typing import List

from isaacsim.core.api.robots.robot import Robot  # type: ignore
from isaacsim.core.utils.prims import create_prim, get_prim_at_path  # type: ignore
from pxr import Gf, PhysxSchema, Usd, UsdPhysics  # type: ignore

from genmanip.core.robot.base import ManipRobotConfig
from genmanip.core.robot.singlearm_manip import SingleArmEmbodiment
from genmanip.core.robot.utils import RobotFactory
from genmanip.utils.planner.curobo.base import CuroboPlanner
from genmanip.utils.standalone.file_utils import load_yaml
from genmanip.utils.usd_utils import get_world_pose_by_prim_path
from genmanip.core.scene.scene_config import RobotConfig

GRIPPER_OPEN = 1.17  # arm_joint_7 rad; 0 = closed
PRE_PICK = [0.0, -0.75, 1.05, 1.1, 0.0, 0.0, GRIPPER_OPEN]  # rena_safety start pose
# base_link origin is 1.1 cm above the wheel bottoms: lift it so the wheels clear the surface
WHEEL_CLEARANCE = 0.012


def rena_description(current_dir: str) -> str:
    # GenManip sits at rena-sim/third_party/GenManip; rena-description is a sibling of rena-sim
    return os.environ.get(
        "RENA_DESCRIPTION", os.path.join(current_dir, "../../../rena-description")
    )


@RobotFactory.register("manip/rena/arm")
class RenaEmbodiment(SingleArmEmbodiment):
    def __init__(self, *args, **kwargs) -> None:
        config = ManipRobotConfig(
            embodiment_name="rena",
            arm_name="rena",
            gripper_name="rena",
            arm_dof_num=6,
            gripper_dof_num=1,
            gripper_open=[GRIPPER_OPEN],
            gripper_close=[0.0],
            default_arm_dof_indices=[0, 1, 2, 3, 4, 5],
            default_gripper_dof_indices=[6],
        )
        super().__init__(config, *args, **kwargs)

    def create_robot(
        self, scene_uid: str, default_config: dict, robot_config: RobotConfig
    ) -> Robot:
        # stand where the scene's franka placeholder stands, as franka/robotiq.py does
        position, orientation = get_world_pose_by_prim_path(
            f"/World/{scene_uid}/franka"
        )
        prim = get_prim_at_path(f"/World/{scene_uid}/franka")
        if prim.IsActive() and prim.IsValid():
            prim.SetActive(False)
        prim_path = f"/World/{scene_uid}/rena"
        prim = create_prim(
            prim_path=prim_path,
            prim_type="Xform",
            usd_path=os.path.join(
                rena_description(default_config["current_dir"]), "usd/rena/rena.usda"
            ),
        )
        # the importer instances link geometry; cameras are authored under the links
        for p in Usd.PrimRange(prim):
            if p.IsInstanceable():
                p.SetInstanceable(False)
        # articulation root is <rena>/Geometry; the solver setters need its physx API applied
        PhysxSchema.PhysxArticulationAPI.Apply(get_prim_at_path(f"{prim_path}/Geometry"))
        position[2] += WHEEL_CLEARANCE
        # the fixed root_joint pins base_link to the world origin (body0 is the non-rigid robot Xform, which
        # PhysX reads as the world): anchor it to the world at the placement pose instead
        joint = UsdPhysics.FixedJoint(get_prim_at_path(f"{prim_path}/Physics/root_joint"))
        joint.GetBody0Rel().SetTargets([])
        joint.GetLocalPos0Attr().Set(Gf.Vec3f(*[float(v) for v in position]))
        joint.GetLocalRot0Attr().Set(Gf.Quatf(*[float(v) for v in orientation]))
        robot = Robot(prim_path=prim_path, name="rena")
        robot.set_solver_position_iteration_count(128)
        robot.set_stabilization_threshold(0.005)
        robot.set_solver_velocity_iteration_count(4)
        robot.set_world_pose(position, orientation)
        # world.reset() restores the default state, captured above at the origin
        robot.set_default_state(position, orientation)
        return robot

    def _initialize(self, default_joint_positions=None):
        super()._initialize(default_joint_positions)
        if default_joint_positions is None:
            self.robot.set_joint_positions(PRE_PICK, joint_indices=self.default_dof_indices)
            self.robot_view.set_joint_position_targets(
                PRE_PICK, joint_indices=self.default_dof_indices
            )

    def set_planner(self, current_dir: str) -> List[CuroboPlanner]:
        cfg = load_yaml(os.path.join(current_dir, "configs/robots/curobo/rena.yml"))
        kin = cfg["robot_cfg"]["kinematics"]
        for key in ("urdf_path", "asset_root_path"):
            kin[key] = kin[key].replace(
                "${RENA_DESCRIPTION}", rena_description(current_dir)
            )
        planner = CuroboPlanner(cfg, self.robot.prim_path)
        # arm_joint_7 (gripper) is locked open in the cuRobo config
        planner.ordered_js_names = [f"arm_joint_{i}" for i in range(1, 7)]
        planner.dof_len = 6
        return [planner]
